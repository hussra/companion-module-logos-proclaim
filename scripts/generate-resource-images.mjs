import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const resourcesDirectory = path.join(rootDirectory, 'resources')
const outputFile = path.join(rootDirectory, 'src', 'resource-images.ts')
const reservedWords = new Set(
	'await break case catch class const continue debugger default delete do else enum export extends false finally for function if implements import in instanceof interface let new null package private protected public return static super switch this throw true try typeof var void while with yield arguments eval'.split(
		' ',
	),
)

function toExportName(filename) {
	const parts = path
		.basename(filename, path.extname(filename))
		.split(/[^a-zA-Z0-9_$]+/)
		.filter(Boolean)
	let name = parts
		.map((part, index) => (index === 0 ? part[0].toLowerCase() + part.slice(1) : part[0].toUpperCase() + part.slice(1)))
		.join('')

	if (!name) name = 'image'
	if (!/^[a-zA-Z_$]/.test(name) || reservedWords.has(name)) name = `image${name[0].toUpperCase()}${name.slice(1)}`

	return name
}

const filenames = (await readdir(resourcesDirectory))
	.filter((filename) => path.extname(filename).toLowerCase() === '.png')
	.sort((left, right) => left.localeCompare(right))

const exports = new Set()
const declarations = []
for (const filename of filenames) {
	const exportName = toExportName(filename)
	if (exports.has(exportName)) {
		throw new Error(`Multiple resource images would create the export "${exportName}"`)
	}
	exports.add(exportName)

	const contents = await readFile(path.join(resourcesDirectory, filename))
	const dataUrl = `data:image/png;base64,${contents.toString('base64')}`
	declarations.push(`export const ${exportName}: string = ${JSON.stringify(dataUrl)}`)
}

const source = `// Generated by scripts/generate-resource-images.mjs; do not edit directly.\n\n${declarations.join('\n\n')}\n`
await writeFile(outputFile, source)
